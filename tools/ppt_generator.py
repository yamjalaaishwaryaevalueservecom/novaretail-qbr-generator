def build_deck():
    """
    Build the final PowerPoint using ADK-generated content.
    """

    content = load_content_plan()

    validate_content_plan(content)
    validate_files(content)

    presentation = Presentation(
        str(TEMPLATE_PATH)
    )

    if len(presentation.slides) != 5:
        raise ValueError(
            "The template must contain exactly 5 slides. "
            f"Found: {len(presentation.slides)}"
        )

    # =====================================================
    # SLIDE 1: EXECUTIVE OVERVIEW
    # =====================================================

    slide = presentation.slides[0]
    slide_content = content["slide1"]

    replace_text(
        slide,
        "deck_title",
        slide_content["title"]
    )

    replace_text(
        slide,
        "subtitle_1",
        slide_content["subtitle"]
    )

    replace_text(
        slide,
        "kpi1_value",
        slide_content["kpi1_value"]
    )

    replace_text(
        slide,
        "kpi1_label",
        slide_content["kpi1_label"]
    )

    replace_text(
        slide,
        "kpi2_value",
        slide_content["kpi2_value"]
    )

    replace_text(
        slide,
        "kpi2_label",
        slide_content["kpi2_label"]
    )

    replace_text(
        slide,
        "kpi3_value",
        slide_content["kpi3_value"]
    )

    replace_text(
        slide,
        "kpi3_label",
        slide_content["kpi3_label"]
    )

    replace_text(
        slide,
        "summary_text",
        slide_content["summary"]
    )

    remove_shape(
        slide,
        "icon_1_label"
    )

    replace_picture(
        slide,
        "icon_1",
        ICON_DIR / slide_content["icon"]
    )

    # =====================================================
    # SLIDE 2: BUSINESS PERFORMANCE
    # =====================================================

    slide = presentation.slides[1]
    slide_content = content["slide2"]

    replace_text(
        slide,
        "title_2",
        slide_content["title"]
    )

    replace_bullets(
        slide,
        "insights_performance",
        slide_content["insights"]
    )

    remove_shape(
        slide,
        "chart_performance_label"
    )

    replace_picture(
        slide,
        "chart_performance",
        CHART_DIR / slide_content["chart"]
    )

    remove_shape(
        slide,
        "icon_2_label"
    )

    replace_picture(
        slide,
        "icon_2",
        ICON_DIR / slide_content["icon"]
    )

    # =====================================================
    # SLIDE 3: CUSTOMER EXPERIENCE
    # =====================================================

    slide = presentation.slides[2]
    slide_content = content["slide3"]

    replace_text(
        slide,
        "title_3",
        slide_content["title"]
    )

    replace_bullets(
        slide,
        "insights_customer",
        slide_content["insights"]
    )

    remove_shape(
        slide,
        "chart_customer_label"
    )

    replace_picture(
        slide,
        "chart_customer",
        CHART_DIR / slide_content["chart"]
    )

    remove_shape(
        slide,
        "icon_3_label"
    )

    replace_picture(
        slide,
        "icon_3",
        ICON_DIR / slide_content["icon"]
    )

    # =====================================================
    # SLIDE 4: OPERATIONAL RISK
    # =====================================================

    slide = presentation.slides[3]
    slide_content = content["slide4"]

    replace_text(
        slide,
        "title_4",
        slide_content["title"]
    )

    replace_bullets(
        slide,
        "insights_risk",
        slide_content["insights"]
    )

    remove_shape(
        slide,
        "chart_risk_label"
    )

    replace_picture(
        slide,
        "chart_risk",
        CHART_DIR / slide_content["chart"]
    )

    remove_shape(
        slide,
        "icon_4_label"
    )

    replace_picture(
        slide,
        "icon_4",
        ICON_DIR / slide_content["icon"]
    )

    # =====================================================
    # SLIDE 5: RECOMMENDATIONS
    # =====================================================

    slide = presentation.slides[4]
    slide_content = content["slide5"]

    replace_text(
        slide,
        "title_5",
        slide_content["title"]
    )

    replace_bullets(
        slide,
        "recommendations_text",
        slide_content["recommendations"]
    )

    replace_text(
        slide,
        "closing_statement",
        slide_content["closing"]
    )

    remove_shape(
        slide,
        "icon_5_label"
    )

    replace_picture(
        slide,
        "icon_5",
        ICON_DIR / slide_content["icon"]
    )

    # =====================================================
    # SAVE FINAL PRESENTATION
    # =====================================================

    OUTPUT_PATH.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    try:
        presentation.save(
            str(OUTPUT_PATH)
        )

    except PermissionError as error:
        raise PermissionError(
            f"Cannot overwrite {OUTPUT_PATH.name}. "
            "Close the presentation in PowerPoint or "
            "File Explorer preview, then run the script again."
        ) from error

    print(
        "Presentation generated successfully:"
    )

    print(OUTPUT_PATH)


# =========================================================
# SCRIPT ENTRY POINT
# =========================================================

if __name__ == "__main__":
    build_deck()